"""
Session 2: the 12 screening metrics for Stryker, with workings for a hand check.

Run from the project folder (after Session 1 has saved the statements):
    python -m src.session2

Outputs:
    outputs/tables/SYK_metrics.csv            the 12 metrics (+ Sharpe), machine-readable
    outputs/tables/SYK_metrics_workings.md    every formula with the numbers plugged in
    outputs/tables/risk_free_rates.csv        the rates used, with their dates
"""
import pandas as pd

from config import settings
from src import data, fundamentals
from src.company_metrics import compute_company_metrics

TICKER = settings.TEST_COMPANY


def risk_free_rates(price_start: pd.Timestamp, valuation_date: pd.Timestamp) -> pd.DataFrame:
    """
    3-month T-bill: average over the 3-year price window (it is compared with a
    3-year average return in the Sharpe ratio).
    10-year Treasury: latest value on or before the valuation date (for the DCF).
    """
    short = data.download_fred(settings.RISK_FREE_SHORT).loc[price_start:valuation_date].dropna()
    long = data.download_fred(settings.RISK_FREE_LONG).loc[:valuation_date].dropna()
    return pd.DataFrame([
        {"rate": "3-month T-bill (Sharpe)", "series": settings.RISK_FREE_SHORT,
         "value": short.mean(), "basis": f"average {short.index[0]:%d %b %Y} – {short.index[-1]:%d %b %Y}"},
        {"rate": "3-month T-bill, latest", "series": settings.RISK_FREE_SHORT,
         "value": short.iloc[-1], "basis": f"as of {short.index[-1]:%d %b %Y}"},
        {"rate": "10-year Treasury (DCF)", "series": settings.RISK_FREE_LONG,
         "value": long.iloc[-1], "basis": f"as of {long.index[-1]:%d %b %Y}"},
    ])


def markdown_table(df: pd.DataFrame) -> str:
    """A pandas table as a GitHub markdown table (no extra library needed)."""
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def main() -> None:
    settings.TABLES_DIR.mkdir(parents=True, exist_ok=True)
    vd = pd.Timestamp(settings.VALUATION_DATE)

    print("Loading data...")
    closes = data.load_close_prices([TICKER, settings.MARKET_BENCHMARK, settings.SECTOR_BENCHMARK])
    statements = data.load_financials(TICKER)
    table, sources = fundamentals.extract_fundamentals(statements)
    flags = fundamentals.missing_items(table, sources)
    rates = risk_free_rates(pd.Timestamp(settings.PRICE_START), vd)
    rates.to_csv(settings.TABLES_DIR / "risk_free_rates.csv", index=False)

    result = compute_company_metrics(
        TICKER, table,
        stock=closes[TICKER], market=closes[settings.MARKET_BENCHMARK], sector=closes[settings.SECTOR_BENCHMARK],
        valuation_date=settings.VALUATION_DATE, risk_free_short=rates.loc[0, "value"],
    )

    # --- machine-readable metrics ---
    rows = [{"metric": k, "name": settings.METRICS[k]["name"], "group": settings.METRICS[k]["group"],
             "higher_is_better": settings.METRICS[k]["higher_is_better"], "value": v}
            for k, v in result.values.items() if k in settings.METRICS]
    rows.append({"metric": "sharpe", "name": "Sharpe ratio", "group": "Reported only",
                 "higher_is_better": True, "value": result.values["sharpe"]})
    pd.DataFrame(rows).to_csv(settings.TABLES_DIR / f"{TICKER}_metrics.csv", index=False)

    # --- human-readable workings ---
    workings = pd.DataFrame(result.workings)
    context = pd.DataFrame(list(result.context.items()), columns=["Input", "Value"])
    rates_view = rates.assign(value=rates["value"].map("{:.2%}".format))[["rate", "value", "basis"]]
    md = [
        f"# {TICKER}: the 12 screening metrics, with workings",
        "",
        f"Valuation date {settings.VALUATION_DATE}. Money in $ millions. "
        f"Generated by `python -m src.session2`.",
        "",
        "## Inputs", "", markdown_table(context), "",
        "## Risk-free rates (FRED)", "", markdown_table(rates_view), "",
        "## Metrics", "", markdown_table(workings), "",
        "## Yahoo labels used", "",
        markdown_table(pd.DataFrame([(k, v or "MISSING") for k, v in sources.items()],
                                    columns=["Item", "Yahoo label"])), "",
        "## Data flags", "",
        *([f"- {f}" for f in flags] or ["- None: every item found under its preferred label."]),
    ]
    (settings.TABLES_DIR / f"{TICKER}_metrics_workings.md").write_text("\n".join(md), encoding="utf-8")

    # --- print ---
    print("\nInputs:")
    print(context.to_string(index=False))
    print("\nRisk-free rates:")
    print(rates_view.to_string(index=False))
    print("\nMetrics:")
    with pd.option_context("display.max_colwidth", 120, "display.width", 250):
        print(workings.to_string(index=False))
    print("\nData flags:", *(flags or ["none"]), sep="\n  ")


if __name__ == "__main__":
    main()
